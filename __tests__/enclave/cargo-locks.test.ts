import { spawnSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';

// Each tool under tools/ is its own Cargo project with its own lock file, and
// the runbook builds them with `--locked`. When a path dependency (the Seal
// crate) gains dependencies, a tool's lock file goes stale and that build stops
// working, while nothing else notices. `cargo metadata --locked` reports a lock
// file that would need rewriting with "cannot update the lock file"; that
// message, and only that one, turns this test red. Registry or download errors
// (for example offline, with no cached index) are not this test's concern.
const ROOT = path.join(__dirname, '..', '..');
const TOOLS = ['tools/seal-release-key', 'tools/seal-setup'];
const STALE_LOCK = 'cannot update the lock file';
const TIMEOUT_MS = 180_000;

// A system-wide rustup install (the layout of the official Rust images) whose
// RUSTUP_HOME is not exported to this process: the gate and the runbook pass
// it to cargo explicitly.
const SYSTEM_RUSTUP_HOME = '/usr/local/rustup';

// The environments to try cargo in, first the one we were given.
function candidateEnvs(): NodeJS.ProcessEnv[] {
  const envs: NodeJS.ProcessEnv[] = [process.env];
  if (!process.env.RUSTUP_HOME && fs.existsSync(SYSTEM_RUSTUP_HOME)) {
    envs.push({ ...process.env, RUSTUP_HOME: SYSTEM_RUSTUP_HOME });
  }
  return envs;
}

// The environment cargo runs in, or why cargo cannot run here. A rustup proxy
// with no toolchain behind it counts as cargo not being installed.
function findCargo(): { env: NodeJS.ProcessEnv } | { unavailable: string } {
  let reason = 'cargo is not installed';
  for (const env of candidateEnvs()) {
    const probe = spawnSync('cargo', ['--version'], { encoding: 'utf8', env });
    if (probe.error) return { unavailable: `cargo is not installed (${probe.error.message})` };
    if (probe.status === 0) return { env };
    reason = `cargo is not installed with a usable toolchain: ${(probe.stderr || '').trim()}`;
  }
  return { unavailable: reason };
}

const cargo = findCargo();
const unavailable = 'unavailable' in cargo ? cargo.unavailable : null;
const cargoEnv = 'env' in cargo ? cargo.env : process.env;

function cargoMetadataLocked(manifest: string) {
  return spawnSync(
    'cargo',
    ['metadata', '--locked', '--offline', '--format-version', '1', '--manifest-path', manifest],
    {
      cwd: ROOT,
      env: cargoEnv,
      encoding: 'utf8',
      maxBuffer: 256 * 1024 * 1024,
      timeout: TIMEOUT_MS,
    },
  );
}

if (unavailable) {
  console.warn(`Skipping the tools' lock file checks: ${unavailable}`);
}
const withCargo = unavailable ? it.skip : it;

function staleLockMessage(tool: string, stderr: string): string {
  return (
    `${tool}/Cargo.lock is out of date with ${tool}/Cargo.toml (or a path dependency's ` +
    `manifest). Refresh it with a plain \`cargo build\` of the tool, without \`cargo update\`, ` +
    `and commit the lock file.\n\ncargo said:\n${stderr}`
  );
}

describe("the tools' lock files", () => {
  withCargo(
    'the stale lock check sees a lock file that cargo would rewrite',
    () => {
      const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'cargo-lock-probe-'));
      try {
        fs.mkdirSync(path.join(dir, 'src'));
        fs.writeFileSync(path.join(dir, 'src', 'lib.rs'), '');
        fs.writeFileSync(
          path.join(dir, 'Cargo.toml'),
          '[package]\nname = "lock-probe"\nversion = "0.1.0"\nedition = "2021"\n\n[workspace]\n',
        );
        // The lock file names no packages at all, so cargo must add this one.
        fs.writeFileSync(
          path.join(dir, 'Cargo.lock'),
          '# This file is automatically @generated by Cargo.\n' +
            '# It is not intended for manual editing.\nversion = 4\n',
        );
        const result = cargoMetadataLocked(path.join(dir, 'Cargo.toml'));
        expect(result.status).not.toBe(0);
        expect(result.stderr).toContain(STALE_LOCK);
      } finally {
        fs.rmSync(dir, { recursive: true, force: true });
      }
    },
    TIMEOUT_MS,
  );

  for (const tool of TOOLS) {
    withCargo(
      `${tool}/Cargo.lock is up to date with its manifest`,
      () => {
        const manifest = path.join(ROOT, tool, 'Cargo.toml');
        expect(fs.existsSync(manifest)).toBe(true);
        expect(fs.existsSync(path.join(ROOT, tool, 'Cargo.lock'))).toBe(true);

        const result = cargoMetadataLocked(manifest);
        const stderr = result.stderr || '';
        if (stderr.includes(STALE_LOCK)) {
          throw new Error(staleLockMessage(tool, stderr));
        }
        if (result.status !== 0) {
          // Not a stale lock file: most often the registry index or a git
          // dependency is not cached for an offline run. Say so, stay green.
          console.warn(`cargo metadata for ${tool} did not finish (not a lock file problem):\n${stderr}`);
        }
      },
      TIMEOUT_MS,
    );
  }
});
