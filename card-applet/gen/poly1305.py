"""Writes Poly.java: Poly1305 (RFC 8439) over whole 16-byte blocks, unrolled.

Ten 13-bit limbs, as in poly1305-donna's 16-bit version: 100 multiplications
per block. h, r and 5*r stay in int local variables across blocks, since this
card has no RAM int arrays. Sums are unsigned 32-bit values: each limb's sum
is carried after five products so it stays below 2^32, and every shift is
`>>>`. r is read from ph[17..32] (bytes, already clamped) and h is left in
p[0..16] as 8-bit limbs for finish(), which adds s from p[68..83] and
writes the tag. This is the generated Poly1305 measured on the J3R180 in
docs/j3r180-measurements.md. Output goes to stdout.
"""


def limb(i, word):
    """Bits 13i..13i+12 of a 128-bit value given as 16-bit words word(0..7)."""
    w, sh = divmod(13 * i, 16)
    e = word(w) if sh == 0 else f"({word(w)} >>> {sh})"
    if sh > 3 and w + 1 < 8:
        e = f"({e} | ({word(w + 1)} << {16 - sh}))"
    return f"{e} & 0x1FFF"


def term(i, j):
    return f"h{j} * r{i-j}" if j <= i else f"h{j} * s{i+10-j}"


L = ["// Generated by gen/poly1305.py. Do not edit.", "package ghostcard;", "",
     "/**", " * Poly1305 (RFC 8439) on a work array p of 102 shorts: h at 0..16, r at 17..32",
     " * (clamped bytes), scratch at 34..67, s at 68..83.", " */",
     "final class Poly {", "", "    private Poly() {", "    }", ""]
L.append("    /** Poly1305 over len bytes of m (whole 16-byte blocks) with r in p[17..32]; leaves h in p[0..16]. */")
L.append("    static void blocks(short[] p, byte[] m, short off, short len) {")
L.append("        int " + ", ".join(f"t{i} = p[{17+2*i}] | (p[{18+2*i}] << 8)" for i in range(8)) + ";")
L.append("        int " + ", ".join(f"r{i} = {limb(i, lambda w: f't{w}')}" for i in range(10)) + ";")
L.append("        int " + ", ".join(f"s{i} = 5 * r{i}" for i in range(1, 10)) + ";")
L.append("        int " + ", ".join(f"h{i} = 0" for i in range(10)) + ";")
L.append("        int " + ", ".join(f"x{i}" for i in range(10)) + ";")
L.append("        int u;")
L.append("        short end = (short) (off + len);")
L.append("        for (short o = off; o < end; o += 16) {")
for i in range(8):
    L.append(f"            t{i} = (m[(short) (o + {2*i})] & 0xFF) | ((m[(short) (o + {2*i+1})] & 0xFF) << 8);")
for i in range(10):
    hi = " + 0x800" if i == 9 else ""
    L.append(f"            h{i} += ({limb(i, lambda w: f't{w}')}){hi};")
L.append("            u = 0;")
for i in range(10):
    L.append(f"            x{i} = u + " + " + ".join(term(i, j) for j in range(5)) + ";")
    L.append(f"            u = x{i} >>> 13;")
    L.append(f"            x{i} = (x{i} & 0x1FFF) + " + " + ".join(term(i, j) for j in range(5, 10)) + ";")
    L.append(f"            u += x{i} >>> 13;")
L.append("            u = 5 * u + (x0 & 0x1FFF);")
L.append("            h0 = u & 0x1FFF;")
L.append("            h1 = (x1 & 0x1FFF) + (u >>> 13);")
for i in range(2, 10):
    L.append(f"            h{i} = x{i} & 0x1FFF;")
L.append("        }")
# Carry fully, then repack the 13-bit limbs as bytes.
L.append("        u = h1 >>> 13; h1 &= 0x1FFF;")
for i in range(2, 10):
    L.append(f"        u += h{i}; h{i} = u & 0x1FFF; u >>>= 13;")
L.append("        u = 5 * u + h0; h0 = u & 0x1FFF; h1 += u >>> 13;")
L.append("        u = 0;")
bits = 0
byte = 0
for i in range(10):
    L.append(f"        u += h{i}{' << ' + str(bits) if bits else ''};")
    bits += 13
    while bits >= 8 and byte < 16:
        L.append(f"        p[{byte}] = (short) (u & 255); u >>>= 8;")
        byte += 1
        bits -= 8
L.append("        p[16] = (short) u;")
L.append("    }")
L += """
    /** Adds the 17-byte number at p[c..] to the one at p[h..], modulo 2^136. */
    private static void add(short[] p, short h, short c) {
        short u = 0;
        for (short j = 0; j < 17; j++) {
            u += (short) (p[(short) (h + j)] + p[(short) (c + j)]);
            p[(short) (h + j)] = (short) (u & 255);
            u = (short) ((u >> 8) & 0xFF);
        }
    }

    /** Reduces h modulo 2^130 - 5, adds s and writes the 16-byte tag to out[off..]. */
    static void finish(short[] p, byte[] out, short off) {
        short j;
        // g = h + 5 - 2^130 at 51..67: the scratch at 34..50 holds 5 - 2^130.
        for (j = 0; j < 17; j++) {
            p[(short) (51 + j)] = p[j];
            p[(short) (34 + j)] = 0;
        }
        p[34] = 5;
        p[50] = 252;
        add(p, (short) 51, (short) 34);
        // Keep g when h + 5 reached 2^130 (g's top bit clear), h otherwise.
        short s = (short) (((p[67] >> 7) & 1) - 1);
        for (j = 0; j < 17; j++) {
            p[j] ^= (short) (s & (p[(short) (51 + j)] ^ p[j]));
        }
        for (j = 0; j < 16; j++) {
            p[(short) (34 + j)] = p[(short) (68 + j)];
        }
        p[50] = 0;
        add(p, (short) 0, (short) 34);
        for (j = 0; j < 16; j++) {
            out[(short) (off + j)] = (byte) p[j];
        }
    }
}""".split("\n")
print("\n".join(L))
