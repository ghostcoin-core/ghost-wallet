"""Writes ChaCha.java: one ChaCha20 block (RFC 8439), XORed into a byte array.

The 16 words stay in int local variables and every rotation is written inline,
so the 20 rounds make no method call. The key (32 bytes) and nonce (12 bytes)
are read from one byte array, key first. The key stream is XORed into
out[off..off+len), where len is 64 or 32, without passing through a block
buffer. This is the generated block measured on the J3R180 in
docs/j3r180-measurements.md, with the probe's fixed key replaced by the
caller's. Output goes to stdout.
"""
SIGMA = [0x61707865, 0x3320646e, 0x79622d32, 0x6b206574]


def word(i):
    """The initial value of state word i, as a Java expression."""
    if i < 4:
        return f"0x{SIGMA[i]:08x}"
    if i < 12:
        return f"k{i - 4}"
    if i == 12:
        return "counter"
    return f"n{i - 13}"


def load(name, at):
    return (f"{name} = (kn[(short) (o + {at})] & 0xFF) | ((kn[(short) (o + {at + 1})] & 0xFF) << 8)"
            f" | ((kn[(short) (o + {at + 2})] & 0xFF) << 16) | (kn[(short) (o + {at + 3})] << 24);")


def qr(a, b, c, d):
    out = []
    for x, y, z, n in ((a, b, d, 16), (c, d, b, 12), (a, b, d, 8), (c, d, b, 7)):
        out.append(f"x{x} += x{y}; x{z} ^= x{x}; x{z} = (x{z} << {n}) | (x{z} >>> {32 - n});")
    return out


L = ["// Generated by gen/chacha.py. Do not edit.", "package ghostcard;", "",
     "/** ChaCha20 (RFC 8439) key-stream blocks. */", "final class ChaCha {", "",
     "    private ChaCha() {", "    }", ""]
L.append("    /**")
L.append("     * XORs ChaCha20 key-stream block `counter` into out[off..off+len); len is 64 or 32.")
L.append("     * The key is kn[o..o+31] and the nonce kn[o+32..o+43].")
L.append("     */")
L.append("    static void xorBlock(byte[] kn, short o, int counter, byte[] out, short off, short len) {")
L.append("        int " + ", ".join(f"k{i}" for i in range(8)) + ", n0, n1, n2;")
for i in range(8):
    L.append("        " + load(f"k{i}", 4 * i))
for i in range(3):
    L.append("        " + load(f"n{i}", 32 + 4 * i))
L.append("        int " + ", ".join(f"x{i} = {word(i)}" for i in range(16)) + ";")
L.append("        for (short r = 0; r < 10; r++) {")
for q in ((0, 4, 8, 12), (1, 5, 9, 13), (2, 6, 10, 14), (3, 7, 11, 15),
          (0, 5, 10, 15), (1, 6, 11, 12), (2, 7, 8, 13), (3, 4, 9, 14)):
    L += ["            " + l for l in qr(*q)]
L.append("        }")
for i in range(16):
    if i == 8:
        L.append("        if (len == 32) {")
        L.append("            return;")
        L.append("        }")
    L.append(f"        x{i} += {word(i)};")
    for b in range(4):
        v = f"x{i}" if b == 0 else f"(x{i} >>> {8*b})"
        L.append(f"        out[off++] ^= (byte) {v};")
L.append("    }")
L.append("}")
print("\n".join(L))
